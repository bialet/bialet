# ---------------------------------------------------------------------------
# Generated routes
# ---------------------------------------------------------------------------

emit_filler() {
  local bytes="$1" written=0 i=0 line
  while ((written < bytes)); do
    line="        <p>Paragraph $i: the quick brown fox jumps over the lazy dog while the benchmark records another sample. </p>"
    printf '%s\n' "$line"
    written=$((written + ${#line} + 1))
    i=$((i + 1))
  done
}

for ((n = 0; n < ROUTES; n++)); do
  printf -v num '%03d' "$n"
  file="$OUT/page-$num.wren"
  paras=0
  if ((LARGE_EVERY > 0)) && ((n == 0 || n % LARGE_EVERY == 0)); then
    paras=$((LARGE_BYTES / 130))
    ((paras > 0)) || paras=1
  fi
  {
    cat <<WREN
// Generated route /page-$num. Part of the "many files" shape the bytecode
// cache and the routing walk have to cope with.
return <!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <title>Page $num</title>
    <link rel="stylesheet" href="/assets/site.css">
  </head>
  <body>
    <main>
      <p class="crumb"><a href="/">Home</a> / page-$num</p>
      <h1>Page $num</h1>
      <p>Generated template route. Small on purpose, except every
      ${LARGE_EVERY}th page which carries a large body.</p>
      <ul>
        {{ ["alpha", "beta", "gamma"].map{|item| <li>{{ item }}</li> } }}
      </ul>
WREN
    if ((paras > 0)); then
      printf '      <section class="filler">\n'
      emit_filler "$LARGE_BYTES"
      printf '      </section>\n'
    fi
    cat <<'WREN'
    </main>
  </body>
</html>
WREN
  } >"$file"
done

