#!/usr/bin/env bash
#
# gen-app.sh - generate one synthetic Bialet app for the benchmark harness.
#
# The app exercises the paths the harness measures:
#   /               DB SELECT + HTML loop (50 rows)
#   /item?id=N      DB read by id, 404 for a missing id
#   /write          POST insert/upsert, 201
#   /api/items      JSON response
#   /session        session + cookie write
#   /module         route importing a shared local _app/shared.wren
#   /render         CPU-heavy HTML loop (600 rows, escaping)
#   /page-NNN       N generated routes; some carry large templates
#   /assets/*       small CSS, ~50 KB JS, ~1 MB binary
#   404.wren        error page
#
# Generated files land under bench/work/apps/site-N (gitignored). Rerunning
# without --force preserves _db.sqlite3, so the 10k-row seed is paid once;
# --force removes the app, including its database.
#
# Usage: gen-app.sh [options]
#   --out DIR             Output directory (default: bench/work/apps/site-1)
#   --name NAME           Site label stored in the app (default: basename)
#   --seed N              Rows to seed into items (default: 10000)
#   --routes N            Generated page-NNN.wren routes (default: 120)
#   --large-every N       Every Nth generated page gets a large template
#                         (default: 17; 0 disables large pages)
#   --large-bytes N       Size of each large template's filler (default: 32768)
#   --js-bytes N          Approximate size of assets/app.js (default: 51200)
#   --force               Remove the app directory first, including its DB
#   --validate            Syntax-check every .wren with build/bialet -t
#   --binary PATH         Binary used by --validate (default: build/bialet)
#   -h, --help            Show this help

set -euo pipefail

# shellcheck source=lib/common.sh
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

OUT="$APPS_DIR/site-1"
NAME=""
SEED=10000
ROUTES=120
LARGE_EVERY=17
LARGE_BYTES=32768
JS_BYTES=51200
FORCE=0
VALIDATE=0
BINARY="$REPO_ROOT/build/bialet"

usage() {
  print_usage_header "${BASH_SOURCE[0]}"
}

need_value() { (($# >= 2)) || die "$1 needs a value"; }

while (($#)); do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --out) need_value "$@"; OUT="$2"; shift 2 ;;
    --out=*) OUT="${1#*=}"; shift ;;
    --name) need_value "$@"; NAME="$2"; shift 2 ;;
    --name=*) NAME="${1#*=}"; shift ;;
    --seed) need_value "$@"; SEED="$2"; shift 2 ;;
    --seed=*) SEED="${1#*=}"; shift ;;
    --routes) need_value "$@"; ROUTES="$2"; shift 2 ;;
    --routes=*) ROUTES="${1#*=}"; shift ;;
    --large-every) need_value "$@"; LARGE_EVERY="$2"; shift 2 ;;
    --large-every=*) LARGE_EVERY="${1#*=}"; shift ;;
    --large-bytes) need_value "$@"; LARGE_BYTES="$2"; shift 2 ;;
    --large-bytes=*) LARGE_BYTES="${1#*=}"; shift ;;
    --js-bytes) need_value "$@"; JS_BYTES="$2"; shift 2 ;;
    --js-bytes=*) JS_BYTES="${1#*=}"; shift ;;
    --force) FORCE=1; shift ;;
    --validate) VALIDATE=1; shift ;;
    --binary) need_value "$@"; BINARY="$2"; shift 2 ;;
    --binary=*) BINARY="${1#*=}"; shift ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
done

is_uint "$SEED" && ((SEED >= 0)) || die "--seed must be a non-negative integer"
if ((SEED < 5000)); then
  warn "seed=$SEED: the db-read workload reads /item?id=5000 and will return 404"
fi
is_uint "$ROUTES" && ((ROUTES >= 0 && ROUTES <= 9000)) || die "--routes must be 0-9000"
is_uint "$LARGE_EVERY" || die "--large-every must be an integer"
is_uint "$LARGE_BYTES" || die "--large-bytes must be an integer"
is_uint "$JS_BYTES" || die "--js-bytes must be an integer"

[[ -n "$OUT" ]] || die "--out must not be empty"
ensure_dir "$(dirname -- "$OUT")"
# A force rebuild deletes the directory. Refuse obviously dangerous targets
# even though everything lives under bench/work by default.
if ((FORCE == 1)); then
  out_abs="$(abs_path "$(dirname -- "$OUT")")/$(basename -- "$OUT")"
  case "$out_abs" in
    "/"|"$HOME"|"$REPO_ROOT"|"$REPO_ROOT/src"|"$REPO_ROOT/docs")
      die "refusing to --force into $OUT" ;;
  esac
fi

NAME="${NAME:-$(basename -- "$OUT")}"

if ((FORCE == 1)) && [[ -e "$OUT" ]]; then
  info "removing $OUT (--force)"
  rm -rf -- "$OUT"
fi
ensure_dir "$OUT"
ensure_dir "$OUT/assets"
ensure_dir "$OUT/api"
ensure_dir "$OUT/_app"
OUT="$(abs_path "$OUT")"

# Remove stale generated routes before writing the new set. The DB and other
# files are left alone so reruns are cheap and idempotent.
find "$OUT" -maxdepth 1 -type f -name 'page-*.wren' -delete 2>/dev/null || true

# ---------------------------------------------------------------------------
# Wren sources
# ---------------------------------------------------------------------------

cat >"$OUT/_migration.wren" <<WREN
// Schema and seed for the benchmark app. Generated by bench/gen-app.sh.
// Schema changes go through Db.migrate; seeding is guarded by a row count so
// restarting an existing app is a single COUNT(*) and does not reinsert rows.

Db.migrate("bench: items schema", \`
  CREATE TABLE IF NOT EXISTS items (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    body TEXT,
    price TEXT,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
  )
\`)

Db.migrate("bench: writes schema", \`
  CREATE TABLE IF NOT EXISTS writes (
    slot INTEGER PRIMARY KEY,
    value TEXT,
    updated_at DATETIME
  )
\`)

// Refresh the label on every start; it is one tiny read/write.
\`INSERT OR REPLACE INTO BIALET_CONFIG (key, val) VALUES ("bench_site_name", ?)\`.query("$NAME")

var existing = \`SELECT COUNT(*) FROM items\`.toNum || 0
if (existing < $SEED) {
  for (i in existing...$SEED) {
    \`INSERT INTO items (name, body, price) VALUES (?, ?, ?)\`.query(
      "item " + i.toString,
      "body text for item " + i.toString + " with <markup> & quotes",
      ((i % 1000)).toString + ".99"
    )
  }
}
WREN

cat >"$OUT/_app/shared.wren" <<'WREN'
// Shared local module imported by /module. Protected by the leading _app/
// directory, so it is never a route on its own.
class Shared {
  static site { "Bialet bench" }

  static label(text) { "[" + text + "]" }

  static price(value) { "$" + value }

  static summary(rows) { "rows: " + rows.count.toString }
}
WREN

cat >"$OUT/index.wren" <<'WREN'
// Home: one DB SELECT, one COUNT and an HTML loop over 50 rows.
var items = `
  SELECT id, name, price FROM items ORDER BY id LIMIT 50
`.fetch
var total = `SELECT COUNT(*) FROM items`.toNum || 0
var site = Config.get("bench_site_name") || "Bialet bench"

return <!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{{ site }}</title>
    <link rel="stylesheet" href="/assets/site.css">
  </head>
  <body>
    <main>
      <h1>{{ site }}</h1>
      <p>{{ total }} rows seeded. Showing the first {{ items.count }}.</p>
      <ul class="items">
        {{ items.map{|item| <li>
          <a href="/item?id={{ item["id"] }}">{{ item["name"] }}</a>
          <span class="price">{{ item["price"] }}</span>
        </li> } }}
      </ul>
      <form method="POST" action="/write">
        <input type="hidden" name="slot" value="7">
        <input name="value" value="hello from the benchmark">
        <button>Write a row</button>
      </form>
      <nav>
        <a href="/render">render</a>
        <a href="/api/items">json</a>
        <a href="/session">session</a>
        <a href="/module">module</a>
        <a href="/page-000">page-000</a>
      </nav>
    </main>
  </body>
</html>
WREN

cat >"$OUT/item.wren" <<'WREN'
// DB read by id. The id is a query parameter, the documented alternative to a
// path segment; a missing row goes through the custom 404.wren page.
var id = Request.get("id") || "1"
var item = `SELECT id, name, body, price, created_at FROM items WHERE id = ?`.first(id)
if (!item) return Response.notFound()

return <!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <title>{{ item["name"] }}</title>
    <link rel="stylesheet" href="/assets/site.css">
  </head>
  <body>
    <main>
      <p class="crumb"><a href="/">Home</a> / item {{ item["id"] }}</p>
      <h1>{{ item["name"] }}</h1>
      <p>{{ item["body"] }}</p>
      <p class="price">{{ item["price"] }}</p>
      <p class="meta">created {{ item["created_at"] }}</p>
    </main>
  </body>
</html>
WREN

cat >"$OUT/write.wren" <<'WREN'
// DB write. INSERT OR REPLACE keeps the table at a fixed 1000 slots, so
// repeated benchmark runs do not grow the database and skew A/B comparisons.
if (!Request.isPost) {
  Response.status(405)
  return <!doctype html>
  <html><body><h1>Method not allowed</h1><p>POST a slot and value.</p></body></html>
}

var slot = Num.fromString(Request.post("slot") || "7") || 7
var value = Request.post("value") || ""
`INSERT OR REPLACE INTO writes (slot, value, updated_at) VALUES (?, ?, CURRENT_TIMESTAMP)`.query(slot, value)

Response.status(201)
return <!doctype html>
<html lang="en">
  <head><meta charset="utf-8"><title>Saved</title></head>
  <body>
    <main>
      <h1>Saved slot {{ slot }}</h1>
      <p>{{ value }}</p>
      <p><a href="/">Home</a></p>
    </main>
  </body>
</html>
WREN

cat >"$OUT/api/items.wren" <<'WREN'
// JSON endpoint. The rows are maps with string values, as SQLite returns them.
var rows = `SELECT id, name, price FROM items ORDER BY id LIMIT 20`.fetch
var total = `SELECT COUNT(*) FROM items`.toNum || 0
Response.json({
  "items": rows,
  "count": rows.count,
  "total": total,
})
WREN

cat >"$OUT/session.wren" <<'WREN'
// Session + cookie endpoint. Session.new() adopts or mints the session id;
// set() stores server-side rows in BIALET_SESSION and Cookie.set sends a
// separate cookie, so each request exercises both paths.
var session = Session.new()
var previous = session.get("hits") || "0"
var hits = (Num.fromString(previous) || 0) + 1
session.set("hits", hits.toString)
session.set("agent", Request.header("User-Agent") || "unknown")
Cookie.set("bench_visitor", session.id)

return <!doctype html>
<html lang="en">
  <head><meta charset="utf-8"><title>Session</title></head>
  <body>
    <main>
      <h1>Session hits: {{ hits }}</h1>
      <p>Session id length: {{ session.id.count }}</p>
      <p><a href="/">Home</a></p>
    </main>
  </body>
</html>
WREN

cat >"$OUT/module.wren" <<'WREN'
import "_app/shared" for Shared

// A route that imports a shared local module: the import is compiled and
// cached with the route, which is what the bytecode cache has to handle.
var rows = `SELECT id, name, price FROM items ORDER BY id LIMIT 5`.fetch

return <!doctype html>
<html lang="en">
  <head><meta charset="utf-8"><title>{{ Shared.site }}</title></head>
  <body>
    <main>
      <h1>{{ Shared.label("shared module") }}</h1>
      <p>{{ Shared.summary(rows) }}</p>
      <ul>
        {{ rows.map{|row| <li>{{ row["name"] }} <span>{{ Shared.price(row["price"]) }}</span></li> } }}
      </ul>
      <p><a href="/">Home</a></p>
    </main>
  </body>
</html>
WREN

cat >"$OUT/render.wren" <<'WREN'
// CPU-heavy HTML: 600 synthetic rows, each interpolated and escaped. No DB
// work, so profiling this route isolates the template/VM path.
var items = []
for (i in 0...600) {
  items.add({
    "id": i,
    "name": "Item <" + i.toString + "> & \"quoted\"",
    "price": ((i * 37) % 1000).toString + ".99",
