}
var rows = items.map{|it| <tr>
  <td>{{ it["id"] }}</td>
  <td>{{ it["name"] }}</td>
  <td>{{ it["price"] }}</td>
</tr> }

return <!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <title>Render</title>
    <link rel="stylesheet" href="/assets/site.css">
  </head>
  <body>
    <main>
      <h1>600 rendered rows</h1>
      <table>
        <thead><tr><th>id</th><th>name</th><th>price</th></tr></thead>
        <tbody>{{ rows }}</tbody>
      </table>
      <p><a href="/">Home</a></p>
    </main>
  </body>
</html>
WREN

cat >"$OUT/404.wren" <<'WREN'
