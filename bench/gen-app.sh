# app.js is filler with plausible shape: ~50 KB is enough that it is a
# meaningful static response without dominating the 1 MB binary.
{
  printf '/* generated benchmark asset - %s bytes target */\n' "$JS_BYTES"
  printf '(function () {\n'
  written=0
  i=0
  while ((written < JS_BYTES)); do
    printf '  function benchStep%d(value) { return (value * %d + %d) %% 1000003; }\n' "$i" "$((i + 7))" "$((i * 13))"
    written=$((written + 70))
    i=$((i + 1))
  done
  printf '  window.benchSteps = %d;\n' "$i"
  printf '})();\n'
} >"$OUT/assets/app.js"

# ~1 MiB binary. Deterministic bytes are fine for the network path; they are
# not compressible in a way that matters to the server (no compression here).
if have python3; then
  python3 - "$OUT/assets/blob.bin" <<'PY'
import sys
open(sys.argv[1], "wb").write(bytes(range(256)) * 4096)
PY
else
  dd if=/dev/zero of="$OUT/assets/blob.bin" bs=1024 count=1024 2>/dev/null
fi

# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------

wren_count="$(find "$OUT" -type f -name '*.wren' | wc -l | tr -d ' ')"
total_bytes="$(du -sk "$OUT" 2>/dev/null | awk '{print $1}')"
info "generated $OUT (label: $NAME)"
printf '    %s .wren files, %s KiB total, %s seeded rows, %s generated routes\n' \
  "$wren_count" "${total_bytes:-?}" "$SEED" "$ROUTES"
printf '    large templates: %s (every %sth page, ~%s bytes of filler)\n' \
  "$([[ "$LARGE_EVERY" == "0" ]] && echo none || echo yes)" "$LARGE_EVERY" "$LARGE_BYTES"
printf '    assets: site.css, app.js (~%s bytes), blob.bin (~1 MiB)\n' "$JS_BYTES"

if ((VALIDATE == 1)); then
  [[ -x "$BINARY" ]] || die "--validate needs an executable binary at $BINARY (run make)"
  BINARY="$(abs_path "$(dirname -- "$BINARY")")/$(basename -- "$BINARY")"
  app_db_existed=0
  [[ -e "$OUT/_db.sqlite3" ]] && app_db_existed=1
  scratch="$(mktemp -d "${TMPDIR:-/tmp}/bialet-validate.XXXXXX")"
  trap 'rm -rf -- "$scratch"' EXIT
  failures=0
  checked=0
  while IFS= read -r -d '' file; do
    checked=$((checked + 1))
    if ! ( cd -- "$scratch" && "$BINARY" -q -d "$scratch/validate.sqlite3" \
        -t "$file" "$OUT" >/dev/null 2>"$scratch/err" ); then
      printf 'syntax error in %s\n' "$file" >&2
      sed 's/^/    /' "$scratch/err" >&2 || true
      failures=$((failures + 1))
    fi
  done < <(find "$OUT" -type f -name '*.wren' -print0)
  rm -rf -- "$scratch"
  trap - EXIT
  if ((app_db_existed == 0)); then
    rm -f -- "$OUT/_db.sqlite3" "$OUT/_db.sqlite3-wal" "$OUT/_db.sqlite3-shm"
  fi
  if ((failures > 0)); then
    die "$failures of $checked generated .wren files failed validation"
  fi
  info "validated $checked .wren files with $BINARY -t"
fi
